#!/usr/bin/env node
/**
 * Checks the area map in scripts/areas/areas.mjs and keeps the CI filters in
 * step with it.
 *
 *   npm run areas:check   verify only (CI)
 *   npm run areas:sync    rewrite .github/e2e-path-filters.yml and
 *                         .github/e2e-outside-filter.yml, then verify
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { AREAS, IGNORED, SHARED, areaPaths, toGlob } from './areas.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const write = process.argv.includes('--write');
const PATH_FILTERS = '.github/e2e-path-filters.yml';
const OUTSIDE_FILTER = '.github/e2e-outside-filter.yml';

const GENERATED = `# Generated by scripts/areas/sync.mjs from scripts/areas/areas.mjs.
# Do not edit by hand: change areas.mjs, then run \`npm run areas:sync\`.`;

function renderPathFilters() {
	const groups = Object.entries(AREAS).map(([name, area]) => [name, areaPaths(area)]);
	groups.push(['shared', SHARED]);
	const body = groups
		.map(([name, paths]) =>
			paths.length === 0
				? `${name}:\n  - '!**'`
				: `${name}:\n${paths.map((path) => `  - ${toGlob(path)}`).join('\n')}`,
		)
		.join('\n');
	return `${GENERATED}
#
# dorny/paths-filter matches these with the default predicate-quantifier: some
# (a file matches a group if it matches any pattern). Do not put a catch-all
# "**" in this file: negations would not exclude it.

${body}
`;
}

function renderOutsideFilter() {
	const claimed = [
		...IGNORED,
		...Object.values(AREAS).flatMap((area) => areaPaths(area).map(toGlob)),
		...SHARED.map(toGlob),
	];
	return `${GENERATED}
#
# Unclassified-change filter for CI end-to-end selection. CI applies it with
# predicate-quantifier: every, so a changed file counts as unclassified only
# when it matches "**" and none of the claimed paths. With the default
# quantifier "some", "**" alone would match and the negations would do nothing.

outside:
  - '**'
${claimed.map((glob) => `  - '!${glob}'`).join('\n')}
`;
}

const problems = [];

// 1. Generated filters match the area map.
for (const [file, content] of [
	[PATH_FILTERS, renderPathFilters()],
	[OUTSIDE_FILTER, renderOutsideFilter()],
]) {
	const path = join(root, file);
	const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
	if (current === content) continue;
	if (write) {
		writeFileSync(path, content);
		console.log(`wrote ${file}`);
	} else {
		problems.push(`${file} is out of date. Run \`npm run areas:sync\`.`);
	}
}

// 2. Every listed path exists, and none is claimed twice.
const owners = new Map();
const claim = (path, owner) => {
	if (!existsSync(join(root, path))) problems.push(`${owner} lists missing path: ${path}`);
	for (const [other, otherOwner] of owners) {
		const overlaps = other === path || path.startsWith(`${other}/`) || other.startsWith(`${path}/`);
		if (overlaps && otherOwner !== owner) {
			problems.push(`${path} (${owner}) overlaps ${other} (${otherOwner})`);
		}
	}
	owners.set(path, owner);
};
for (const [name, area] of Object.entries(AREAS)) {
	for (const path of areaPaths(area)) claim(path, name);
}
for (const path of SHARED) claim(path, 'shared');

// 3. Every tracked file under src/ belongs to an area or to shared code.
const tracked = execFileSync(
	'git',
	['ls-files', '--cached', '--others', '--exclude-standard', 'src'],
	{
		cwd: root,
		encoding: 'utf8',
	},
)
	.split('\n')
	.filter(Boolean)
	.filter((file) => !file.endsWith('.md') && existsSync(join(root, file)));
const claimed = [...owners.keys()];
const unclassified = tracked.filter(
	(file) => !claimed.some((path) => file === path || file.startsWith(`${path}/`)),
);
if (unclassified.length > 0) {
	problems.push(
		`Files under src/ that belong to no area. Add them to scripts/areas/areas.mjs:\n${unclassified
			.map((file) => `    ${file}`)
			.join('\n')}`,
	);
}

if (problems.length > 0) {
	console.error(`Area map check failed:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
	process.exit(1);
}
console.log(`Area map OK: ${Object.keys(AREAS).length} areas, ${tracked.length} files under src/.`);
